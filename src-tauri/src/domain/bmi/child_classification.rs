pub fn bmi_child_classification(age_months: i32, gender: Gender, bmi: f64) -> BmiClassification {
    let (z_minus_3, z_minus_2, _, _, z_1, z_2, z_3) = get_bmi_child_z_scores(age_months, gender);

    if bmi <= z_minus_3 {
        return BmiClassification::SevereThinness;
    }
    if bmi <= z_minus_2 {
        return BmiClassification::Thinness;
    }
    if bmi <= z_1 {
        return BmiClassification::NormalWeight;
    }
    if bmi <= z_2 {
        return BmiClassification::OverWeight;
    }
    if bmi <= z_3 {
        return BmiClassification::Obesity;
    }
    BmiClassification::SevereObesity
}

pub fn calculate_ideal_weight_child(age_months: i32, gender: Gender, height: f64) -> [f64; 3] {
    let (_, z_minus_2, _, z_0, z_1, _, _) = get_bmi_child_z_scores(age_months, gender);

    let height_squared = height * height;

    [
        z_minus_2 * height_squared,
        z_0 * height_squared,
        z_1 * height_squared,
    ]
}
